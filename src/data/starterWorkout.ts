import { WorkoutWeek } from "../types";

const localDateString = (date: Date) => {
  const year = date.getFullYear();
  const month = String(date.getMonth() + 1).padStart(2, "0");
  const day = String(date.getDate()).padStart(2, "0");
  return `${year}-${month}-${day}`;
};

export const getCurrentWeekStart = () => {
  const date = new Date();
  const daysFromMonday = (date.getDay() + 6) % 7;
  date.setHours(12, 0, 0, 0);
  date.setDate(date.getDate() - daysFromMonday);
  return localDateString(date);
};

export const formatWorkoutWeek = (startDate: string) => {
  const [year, month, day] = startDate.split("-").map(Number);
  const date = new Date(year, month - 1, day, 12);
  const end = new Date(date);
  end.setDate(end.getDate() + 6);
  const startLabel = date.toLocaleDateString("en-US", { month: "short", day: "numeric" });
  const endLabel = end.toLocaleDateString("en-US", { month: date.getMonth() === end.getMonth() ? undefined : "short", day: "numeric" });
  return `${startLabel} – ${endLabel}`;
};

