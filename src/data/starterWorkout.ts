export const cloneWorkoutWeek = (week: WorkoutWeek, startDate: string): WorkoutWeek => ({
  ...week,
  id: crypto.randomUUID(),
  startDate,
  title: formatWorkoutWeek(startDate),
  days: week.days.map(day => ({
    ...day,
    id: crypto.randomUUID(),
    exercises: day.exercises.map(exercise => ({
      ...exercise,
      id: crypto.randomUUID(),
      completed: false,
    })),
  })),
});
